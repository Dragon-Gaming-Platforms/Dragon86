#define HAVE_STRTOK_R 1
#define HAVE_STRCASECMP 1
#define HAVE_STRNCASECMP 1
#define HAVE_STRERROR_R 1
#define HAVE_POSIX_STRERROR_R 1
#define HAVE_WRITEV 1
#define HAVE_PIPE 1
#define HAVE_ALARM 1
#define HAVE_UTIME 1
#define HAVE_UTIMES 1
#define HAVE_GETEUID 1
#define HAVE_ACCESS 1
#define HAVE_FTRUNCATE 1
#define HAVE_SOCKETPAIR 1
#define HAVE_INET_PTON 1
#define HAVE_INET_NTOP 1
#define HAVE_BASENAME 1
#define HAVE_GMTIME_R 1
#define HAVE_LOCALTIME_R 1
#define HAVE_TIMEGM 1
#define HAVE_MSG_NOSIGNAL 1
#define HAVE_IFADDRS_H 1
#define HAVE_SYS_UN_H 1
#define HAVE_LONGLONG 1
#define HAVE_CLOCK_GETTIME 1
#define HAVE_MONOTONIC_CLOCK 1
#define HAVE_CLOCK_GETTIME_MONOTONIC 1
#define HAVE_SCHED_YIELD 1
#define HAVE_GETRLIMIT 1
#define HAVE_SETRLIMIT 1
#define ENABLE_IPV6 1
#define CURL_DISABLE_LDAP 1
#define CURL_DISABLE_LDAPS 1
#define CURL_DISABLE_SMB 1
#define CURL_DISABLE_GOPHER 1
#define CURL_DISABLE_MQTT 1
#define CURL_DISABLE_TELNET 1
#define CURL_DISABLE_DICT 1
#define CURL_DISABLE_TFTP 1
#define CURL_DISABLE_POP3 1
#define CURL_DISABLE_IMAP 1
#define CURL_DISABLE_SMTP 1
#define CURL_DISABLE_RTSP 1
/* Where the guest keeps its roots; see installGitTransport() in the bridge. */
#define CURL_CA_BUNDLE "/etc/ssl/certs/ca-certificates.crt"
#define OS "x86-linux-musl"
#define CURL_OS "x86-linux-musl"
CONFIG
  ( cd "$WORK/src/curl-curl-$CURL_VERSION"
    mkdir -p lib/x86-unknown-linux-musl
    make -C lib -f Makefile.mk CFG=-mbedtls-zlib-ipv6 \
      CC="$ZIG cc -target $ZIG_TARGET" AR="$ZIG ar" \
      MBEDTLS_PATH="$WORK/prefix" ZLIB_PATH="$WORK/prefix" \
      CFLAGS="-O2 -fPIC -DHAVE_CONFIG_H" libcurl.a -j"$(nproc)" >/dev/null
    cp lib/libcurl.a "$WORK/prefix/lib/"
    mkdir -p "$WORK/prefix/include/curl"
    cp include/curl/*.h "$WORK/prefix/include/curl/" )
fi

# --------------------------------------------------------- git-remote-http --
# Only the transport is needed. git's build wants zlib on its own link line
# (-lz), so point LDFLAGS at the static zlib; NO_OPENSSL is required because
# curl (not git) does the TLS here, and musl's regex has no REG_STARTEND.
say "git-remote-http"
( cd "$WORK/src/git-$GIT_VERSION"
  make -j"$(nproc)" git-remote-http \
    CC="$ZIG cc -target $ZIG_TARGET" AR="$ZIG ar" \
    CURL_CFLAGS="-I$WORK/prefix/include" \
    CURL_LDFLAGS="$WORK/prefix/lib/libcurl.a $WORK/prefix/lib/libmbedtls.a $WORK/prefix/lib/libmbedx509.a $WORK/prefix/lib/libmbedcrypto.a $WORK/prefix/lib/libz.a" \
    CFLAGS="-O2 -I$WORK/prefix/include" LDFLAGS="-L$WORK/prefix/lib" \
    NO_GETTEXT=1 NO_TCLTK=1 NO_PERL=1 NO_PYTHON=1 NO_RUST=1 NO_OPENSSL=1 \
    NO_INSTALL_HARDLINKS=1 NO_ICONV=1 NO_REGEX=NeedsStartEnd NO_EXPAT=1 >/dev/null
  cp git-remote-http "$WORK/bin/git-remote-http"
  strip "$WORK/bin/git-remote-http" )

# --------------------------------------------------------------- CA bundle --
# The same Mozilla root store curl, Firefox and Python's `certifi` ship.
if [ ! -f "$WORK/ca-certificates.crt" ]; then
  say "CA bundle (certifi)"
  ( cd "$WORK"
    python3 -m pip download certifi=="$CERTIFI_VERSION" --no-deps -d . >/dev/null
    python3 - "$WORK/ca-certificates.crt" <<'PY'
import glob, sys, zipfile
whl = glob.glob("certifi-*.whl")[0]
with zipfile.ZipFile(whl) as z:
    name = next(n for n in z.namelist() if n.endswith("cacert.pem"))
    open(sys.argv[1], "wb").write(z.read(name))
PY
  )
fi

# ----------------------------------------------------------------- install --
cp "$WORK/bin/git-remote-http" "$REPO/public/v86/git-remote-http.tmp"
gzip -9 -n -c "$WORK/bin/git-remote-http" > "$REPO/public/v86/git-remote-http.gz"
rm -f "$REPO/public/v86/git-remote-http.tmp"
cp "$WORK/ca-certificates.crt" "$REPO/public/v86/ca-certificates.crt"
say "wrote public/v86/git-remote-http.gz ($(wc -c < "$REPO/public/v86/git-remote-http.gz") bytes)"
say "wrote public/v86/ca-certificates.crt ($(wc -c < "$REPO/public/v86/ca-certificates.crt") bytes)"
say "check it: printf 'capabilities\\n\\n' | public/v86 tests, see tools/test-guest-scripts.mjs"
