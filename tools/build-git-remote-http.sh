#!/bin/sh
# Build public/v86/git-remote-http.gz — the guest's HTTPS transport.
#
# Why this exists
# ---------------
# The git in the guest is a static x86-musl build configured WITHOUT curl (see
# VENDORED.md). git keeps its HTTP transports in separate programs and looks
# them up in `git --exec-path` (/usr/lib/git-core). So the guest only needs
# `git-remote-http` (+ a `git-remote-https` alias) built with libcurl, and a CA
# bundle the libcurl trusts; then `git clone https://…` is a real clone.
#
# Nothing here ships except that one binary and the CA bundle:
#   public/v86/git-remote-http.gz     (4.3 MB stripped, 1.9 MB gzipped)
#   public/v86/ca-certificates.crt    (Mozilla roots, from PyPI's `certifi`)
#
# Requirements: this script downloads sources from codeload.github.com and the
# zig toolchain from npm (package @oven/zig) — no prebuilt binaries — so it runs
# offline-ish in CI but needs both registries. It takes about two minutes.
#
#   tools/build-git-remote-http.sh            build and install into public/v86/
#   WORK=/tmp/d86-git-build tools/…           keep the build tree elsewhere
#
# Versions are pinned below; bumping any of them means rebuilding all of it,
# because libcurl and mbedTLS are linked statically into the helper.
set -eu

REPO=$(cd "$(dirname "$0")/.." && pwd)
WORK=${WORK:-/tmp/d86-git-build}
ZIG_TARGET=x86-linux-musl

GIT_VERSION=2.49.1
CURL_VERSION=8_11_1
MBEDTLS_VERSION=3.6.2
ZLIB_VERSION=1.3.1
ZIG_PKG=@oven/zig@0.11.0-dev.2401
CERTIFI_VERSION=2026.10.23

mkdir -p "$WORK/src" "$WORK/prefix/lib" "$WORK/prefix/include" "$WORK/bin"

say() { printf '== %s\n' "$*"; }

# ---------------------------------------------------------------- toolchain --
if [ ! -x "$WORK/zig/zig" ]; then
  say "zig $ZIG_PKG from npm"
  ( cd "$WORK" && [ -f package.json ] || npm init -y >/dev/null
    npm i --no-audit --no-fund "$ZIG_PKG" >/dev/null )
  ln -sfn "$WORK/node_modules/@oven/zig-linux-x64" "$WORK/zig"
fi
ZIG="$WORK/zig/zig"
"$ZIG" version

# ------------------------------------------------------------------ sources --
fetch() { # owner/repo tag file
  [ -f "$WORK/src/$3" ] || {
    say "fetch $1@$2"
    curl -sSL -o "$WORK/src/$3" "https://codeload.github.com/$1/tar.gz/refs/tags/$2"
  }
  [ -d "$WORK/src/$(basename "$3" .tgz)" ] || tar xzf "$WORK/src/$3" -C "$WORK/src"
}
fetch git/git "v$GIT_VERSION" git.tgz
fetch curl/curl "curl-$CURL_VERSION" curl.tgz
fetch Mbed-TLS/mbedtls "v$MBEDTLS_VERSION" mbedtls.tgz
fetch madler/zlib "v$ZLIB_VERSION" zlib.tgz

# --------------------------------------------------------------------- zlib --
if [ ! -f "$WORK/prefix/lib/libz.a" ]; then
  say "zlib"
  ( cd "$WORK/src/zlib-$ZLIB_VERSION"
    CC="$ZIG cc -target $ZIG_TARGET" ./configure --static --prefix="$WORK/prefix" >/dev/null
    make -j"$(nproc)" libz.a >/dev/null
    cp libz.a "$WORK/prefix/lib/"; cp zlib.h zconf.h "$WORK/prefix/include/" )
fi

# ------------------------------------------------------------------ mbedtls --
# TLS. Apache-2.0. Built with its own Makefile (needs no configure, no cmake).
if [ ! -f "$WORK/prefix/lib/libmbedtls.a" ]; then
  say "mbedtls"
  ( cd "$WORK/src/mbedtls-$MBEDTLS_VERSION"
    make CC="$ZIG cc -target $ZIG_TARGET" AR="$ZIG ar" CFLAGS="-O2 -fPIC" lib -j"$(nproc)" >/dev/null
    mkdir -p "$WORK/prefix/include/mbedtls" "$WORK/prefix/include/psa"
    cp include/mbedtls/*.h "$WORK/prefix/include/mbedtls/"
    cp include/psa/*.h "$WORK/prefix/include/psa/"
    cp library/*.a "$WORK/prefix/lib/" )
fi

# ------------------------------------------------------------------- libcurl --
# curl's git tree has no ./configure (it is generated by autotools, which is not
# installed here), but it ships lib/Makefile.mk — a hand-written makefile for
# exactly this case. It expects the platform macros autoconf would emit, so the
# config header below stands in for them (checked against musl/i386: 32-bit
# int/long/size_t/void*, 64-bit off_t/time_t).
if [ ! -f "$WORK/prefix/lib/libcurl.a" ]; then
  say "libcurl (mbedTLS, static)"
  cat > "$WORK/src/curl-curl-$CURL_VERSION/lib/curl_config.h" <<'CONFIG'
